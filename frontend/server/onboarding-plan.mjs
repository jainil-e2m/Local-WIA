/**
 * Resolve a destination from the WHOLE selected package, in a fixed order.
 *
 * Returns `{ space, confirmed, evidence, decision, manualSetup }`. A null
 * space means manual setup: the UI shows the reason and approval is blocked.
 */
export const resolveDestination = (offers = []) => {
  const selected = [...offers].filter((k) => OFFERS[k]);
  if (!selected.length) {
    return {
      space: null,
      confirmed: false,
      manualSetup: true,
      evidence: "No offer selected.",
      decision: "Pick the package the client actually signed.",
    };
  }
  const exact = PACKAGE_DESTINATIONS[packageKey(selected)];
  if (exact) {
    const forbidden = exact.space && FORBIDDEN_SPACES.includes(exact.space);
    return {
      ...exact,
      space: forbidden ? null : exact.space,
      manualSetup: !exact.space || !exact.confirmed || Boolean(forbidden),
      ...(forbidden
        ? { evidence: `${exact.evidence} The mapped space is archived and is refused.` }
        : {}),
    };
  }
  /* An unlisted combination is not guessed at. Combining, say, Elevate with a
     standalone accelerator is a business arrangement nobody has described. */
  return {
    space: null,
    confirmed: false,
    manualSetup: true,
    evidence: `No approved destination exists for the combination ${selected
      .map((k) => OFFERS[k].label)
      .join(" + ")}. Destinations are approved per package, never assembled from parts.`,
    decision: "Confirm with Whitney whether this combination is sold, and where it belongs.",
  };
};

