/* The template list carries a versioning suffix that the CLIENT's copy does
   not — Ridgefield's list is plain "Google + Meta Onboarding". Strip it so the
   destination preview shows the name that would actually be created. */
const destinationListName = (templateListName) =>
  templateListName.replace(/\s*\(version \d+\)\s*$/i, "").trim();

export const addDays = (isoDate, days) => {
  const base = new Date(isoDate);
  if (Number.isNaN(base.getTime())) return null;
  base.setUTCDate(base.getUTCDate() + days);
  return base.toISOString().slice(0, 10);
};

/** The offset a phase carries, from the diffed cadence. */
const phaseOffset = (phase) =>
  phase && Object.prototype.hasOwnProperty.call(PHASE_WEEK, phase)
    ? PHASE_WEEK[phase] * 7
    : null;

/**
 * The scheduling rule for one task: which anchor, how far after it, and how
 * confident we are that the rule is theirs rather than ours.
 */
export const scheduleRuleFor = (templateKey, phase) => {
  if (!phase) {
    return {
      anchor: null,
      offsetDays: null,
      confirmed: false,
      why: "No Phase set on the template task — there is no scheduling rule to apply.",
    };
  }
  const mapped = PHASE_ANCHOR[templateKey]?.[phase];
  const offset = phaseOffset(phase);
  if (!mapped) {
    return {
      anchor: null,
      offsetDays: offset,
      confirmed: false,
      why: `Phase "${phase}" is on the template but no anchor has been agreed for it. It is not schedulable until one is.`,
    };
  }
  if (offset === null) {
    return {
      anchor: mapped.anchor,
      offsetDays: null,
      confirmed: false,
      why: `Phase "${phase}" hangs off ${ANCHORS[mapped.anchor].label}, but no interval was observed for it. Proposed as same-day; confirm before relying on it.`,
    };
  }
  return {
    anchor: mapped.anchor,
    offsetDays: offset,
    confirmed: mapped.confirmed,
    why: mapped.confirmed
      ? `${ANCHORS[mapped.anchor].label} + ${offset} days, from the cadence diffed off Ridgefield's live list (n=1 — a proposal to confirm).`
      : `PROPOSED: ${ANCHORS[mapped.anchor].label} + ${offset} days. No dates were observed for this phase.`,
  };
};


/**
 * Build the editable draft.
 *
 * @param {object} input
 * @param {string[]} input.offers        Selected offer keys.
 * @param {string} [input.signatureDate] ISO date the alert pair completed.
 * @param {Record<string,string>} [input.anchorDates]
 *        Known anchor dates, keyed by anchor id. Absent in wave 1. Supplying
 *        one dates the tasks that hang off THAT anchor and nothing else.
 */
export const buildDraft = ({
  offers = [],
  signatureDate,
  anchorDates = {},
  projectName,
} = {}) => {
  const selected = offers.filter((key) => OFFERS[key]);
  const warnings = [];

  const anchors = { ...anchorDates };
  if (signatureDate && !anchors.signed_and_paid) anchors.signed_and_paid = signatureDate;
  for (const [key, value] of Object.entries(anchors)) {
    if (!ANCHORS[key]) {
      delete anchors[key];
      warnings.push(`Unknown anchor "${key}" ignored.`);
      continue;
    }
    if (Number.isNaN(new Date(value).getTime())) {
      delete anchors[key];
      warnings.push(`Anchor date "${value}" for ${ANCHORS[key].label} could not be parsed.`);
    }
  }

  const templateKeys = [];
  for (const offer of selected) {
    for (const key of OFFER_TO_TEMPLATES[offer] ?? []) {
      if (!templateKeys.includes(key)) templateKeys.push(key);
    }
    if (!(OFFER_TO_TEMPLATES[offer] ?? []).length) {
      warnings.push(
        `${OFFERS[offer].label}: no ClickUp onboarding template is mapped to this offer yet, so it contributes no tasks.`,
      );
    }
  }

  const destination = resolveDestination(selected);
  if (destination.manualSetup) {
    warnings.push(
      `No approved ClickUp destination for this package. ${destination.evidence} Routed to manual setup; approval is blocked until a destination is agreed.`,
    );
  }

  const tasks = [];
  const lists = [];

  for (const key of templateKeys) {
    const template = DATA.templates[key];
    if (!template) continue;
    const listName = destinationListName(template.listName);
    lists.push({
      key,
      name: listName,
      sourceListName: template.listName,
      listId: template.listId,
      taskCount: template.taskCount,
    });

    /* Parent names, so a subtask can say what it is a subtask OF. The draft
       kept `isSubtask` and dropped the relationship, which left 135 rows
       reading as free-floating tasks with names like "Send email update". */
    const nameById = new Map(template.tasks.map((t) => [t.sourceId, t.name]));

    for (const task of template.tasks) {
      const rule = scheduleRuleFor(key, task.phase);

      /* Role=Client is THEIR marker for client-gated work and never gets a
         date — a due date there goes overdue through no fault of the
         assignee, and on a team that only ticks boxes in ClickUp that is how
         the tool stops being trusted. It becomes a WAITING state with an
         internal owner and a follow-up date instead. */
      let dueState;
      let dueDate = null;
      let dueAnchor = null;

      if (task.dueState === "gated" || task.role === "Client") {
        dueState = "gated";
        dueAnchor = "Client-gated — waiting state, never a deadline";
      } else if (rule.anchor && rule.offsetDays !== null && anchors[rule.anchor]) {
        dueState = "dated";
        dueDate = addDays(anchors[rule.anchor], rule.offsetDays);
        dueAnchor = `${ANCHORS[rule.anchor].label} +${rule.offsetDays}d`;
      } else if (rule.anchor && rule.offsetDays !== null) {
        /* A rule exists; the anchor date does not yet. Where that anchor is
           a CLIENT DECISION rather than a booking, say so — it is a waiting
           state with an internal owner, and no date will ever be predicted
           for it. */
        dueState = "awaiting_anchor";
        dueAnchor = ANCHORS[rule.anchor].clientGated
          ? `Waiting on the client: ${ANCHORS[rule.anchor].label}`
          : `${ANCHORS[rule.anchor].label} +${rule.offsetDays}d`;
      } else {
        /* NO RULE AT ALL. Distinct from awaiting an anchor, and the
           distinction is the point: 66 of the 92 ads tasks are here, and
           calling them "waiting for kickoff" said they would date themselves
           when a call was booked. They will not. */
        dueState = "unscheduled";
        dueAnchor = rule.why;
      }

      tasks.push({
        id: `${key}-${task.sourceId}`,
        sourceId: task.sourceId,
        title: task.name,
        /* Carries the DESTINATION LIST, so the UI groups by the list each task
           lands in rather than by an abstract template name. */
        template: listName,
        templateKey: key,
        assignee: task.resolvedAssignee,
        assigneeConfidence: task.assigneeConfidence,
        assigneeInTemplate: task.assigneeInTemplate,
        role: task.role,
        phase: task.phase,
        dueDate,
        dueState,
        dueAnchor,
        /* Which anchor moves this row when a call is rescheduled. */
        anchorKey: rule.anchor,
        scheduleConfirmed: rule.confirmed,
        scheduleNote: rule.why,
        /* CALCULATED vs MANUAL. A reschedule recomputes calculated dates and
           leaves manual ones alone; without the distinction a reviewer's
           deliberate override was indistinguishable from a stale derived
           date, so the previous code skipped BOTH. */
        dateSource: dueDate ? "calculated" : null,
        isSubtask: Boolean(task.parentId),
        parentId: task.parentId ? `${key}-${task.parentId}` : null,
        parentTitle: task.parentId ? (nameById.get(task.parentId) ?? null) : null,
        /* Context the reviewer needs and the draft used to drop. */
        hasDescription: Boolean(task.hasDescription),
        checklistItems: task.checklistItems ?? [],
        offsetDays: rule.offsetDays,
        note: task.portedFromV1
          ? "Ported from the superseded v1 template — the only written procedure for this exists there. Confirm it is still required."
          : null,
        include: true,
        /* Set by a reviewer who consciously defers an unresolved item. */
        deferredTo: null,
      });
    }
  }

  /* Kept KEYED rather than as free text, so applying an anchor date can
     retire exactly the warning it answers. As a flat list the "waiting for a
     kickoff" line survived into wave 2 and sat directly under a banner
     saying the date was known. */
  const anchorWarnings = {};
  const awaiting = tasks.filter((t) => t.dueState === "awaiting_anchor");
  if (awaiting.length) {
    const byAnchor = {};
    for (const t of awaiting) byAnchor[t.anchorKey] = (byAnchor[t.anchorKey] ?? 0) + 1;
    for (const [key, n] of Object.entries(byAnchor)) {
      anchorWarnings[key] = ANCHORS[key].clientGated
        ? `${n} task(s) wait on the client: ${ANCHORS[key].label}. These stay as waiting states with an internal owner and a follow-up date — no deadline is invented for them.`
        : `${n} task(s) wait on ${ANCHORS[key].label}. Enter that date when the call is booked and only those tasks fill in.`;
    }
  }

  const unscheduled = tasks.filter((t) => t.dueState === "unscheduled").length;
  if (unscheduled) {
    warnings.push(
      `${unscheduled} task(s) have NO scheduling rule in the template — they will never date themselves from any call. Give them an owner and a manual date, or accept them as undated.`,
    );
  }

  const ambiguous = tasks.filter((t) => t.assigneeConfidence === "ambiguous" && t.include).length;
  if (ambiguous) {
    warnings.push(
      `${ambiguous} task(s) carry Role "Ads Manager", which splits between Carmen (Google) and Jacqueline (Meta). Confirm each before approving.`,
    );
  }
  const heuristic = tasks.filter((t) => t.assigneeConfidence === "heuristic").length;
  if (heuristic) {
    warnings.push(`${heuristic} Ads Manager task(s) were split by keyword, not by a rule they gave us.`);
  }

  const ported = tasks.filter((t) => t.note).length;
  if (ported) {
    warnings.push(
      `${ported} task(s) were carried over from the superseded v1 template. Confirm they are still required.`,
    );
  }

  return {
    tasks,
    templates: templateKeys,
    lists,
    destination: {
      model: DESTINATION.model,
      space: destination.space,
      confirmed: destination.confirmed,
      manualSetup: destination.manualSetup,
      evidence: destination.evidence,
      decision: destination.decision ?? null,
      folder: projectName ?? null,
    },
    anchors,
    anchorWarnings,
    anchorCatalogue: ANCHORS,
    signatureDate: signatureDate ?? null,
    generatedAt: new Date().toISOString(),
    /* No longer a placeholder: this is their real template data. The UI badge
       flips off with this flag. */
    placeholder: false,
    sourceNote: `Read from ClickUp ${String(TEMPLATE_SOURCE.fetchedAt).slice(0, 10)} — read-only, no write has ever been issued.`,
    warnings,
  };
};

/**
 * What applying an anchor date WOULD change, without changing it.
 *
 * A reviewer rescheduling a postponed call needs to see the damage first —
 * how many dates move, which ones, and which of their own overrides are being
 * preserved. The previous function applied silently and skipped every row
 * that already had a date, including dates the system itself had calculated,
 * so a moved call could not actually move anything.
 */
export const previewAnchorChange = (draft, anchorKey, isoDate) => {
  const changes = [];
  const preserved = [];
  if (!ANCHORS[anchorKey] || Number.isNaN(new Date(isoDate).getTime())) {
    return { changes, preserved, valid: false };
  }
  for (const task of draft?.tasks ?? []) {
    if (task.anchorKey !== anchorKey) continue;
    if (task.dueState === "gated") continue;
    if (task.offsetDays === null) continue;
    const next = addDays(isoDate, task.offsetDays);
    if (task.dateSource === "manual") {
      preserved.push({ id: task.id, title: task.title, keeps: task.dueDate, wouldBe: next });
      continue;
    }
    if (task.dueDate === next) continue;
    changes.push({ id: task.id, title: task.title, from: task.dueDate, to: next });
  }
  return { changes, preserved, valid: true };
};

/** Counts for the review header, recomputed live as a reviewer edits.

    THE UNSAFE SET is what approval is now blocked on. A warning that can be
    scrolled past is not a control: the previous panel enabled Approve with
    14 unowned tasks, 28 unconfirmed assignees and no agreed destination, and
    said so only in a pill. Each of these is either resolved, or deliberately
    deferred to a named person — never both ignored and approved. */
export const summarizeDraft = (draft) => {
  const all = draft?.tasks ?? [];
  const tasks = all.filter((task) => task.include !== false);
  const deferred = (t) => Boolean(t.deferredTo);

  const missingOwner = tasks.filter(
    (t) => !t.assignee && t.role !== "Client" && !deferred(t),
  );
  const ambiguousOwner = tasks.filter(
    (t) => ["ambiguous", "heuristic"].includes(t.assigneeConfidence) && !deferred(t),
  );
  const unscheduled = tasks.filter((t) => t.dueState === "unscheduled" && !deferred(t));
  const portedUnconfirmed = tasks.filter((t) => t.note && !deferred(t));

  return {
    total: tasks.length,
    dated: tasks.filter((t) => t.dueState === "dated").length,
    /* Two different things, deliberately not summed. One waits for a call
       and will date itself; the other never will. */
    awaitingAnchor: tasks.filter((t) => t.dueState === "awaiting_anchor").length,
    unscheduled: unscheduled.length,
    gated: tasks.filter((t) => t.dueState === "gated").length,
    excluded: all.length - tasks.length,
    deferred: tasks.filter(deferred).length,
    manualDates: tasks.filter((t) => t.dateSource === "manual").length,
    unresolvedAssignee: missingOwner.length,
    needsConfirm: ambiguousOwner.length,
    portedUnconfirmed: portedUnconfirmed.length,
    /* The gate. Missing owners and ambiguous owners block; a task with no
       scheduling rule does not — undated work is normal in their workspace,
       an unowned task is not. */
    blockers: [
      ...(draft?.destination?.manualSetup
        ? [
            {
              kind: "destination",
              count: 1,
              label: "No approved ClickUp destination for this package",
            },
          ]
        : []),
      ...(missingOwner.length
        ? [{ kind: "owner", count: missingOwner.length, label: "tasks with no owner" }]
        : []),
      ...(ambiguousOwner.length
        ? [
            {
              kind: "ambiguous",
              count: ambiguousOwner.length,
              label: "tasks whose owner was guessed, not given",
            },
          ]
        : []),
    ],
  };
};

/** Which exception a task falls into, for the review filters. */
export const taskExceptions = (task) => {
  const out = [];
  if (task.deferredTo) out.push("deferred");
  if (!task.assignee && task.role !== "Client") out.push("no_owner");
  if (["ambiguous", "heuristic"].includes(task.assigneeConfidence)) out.push("ambiguous_owner");
  if (task.dueState === "unscheduled") out.push("no_rule");
  if (task.dueState === "gated") out.push("client_gated");
  if (task.note) out.push("ported");
  return out;
};

/* ── WHAT THE SHARED PROVISIONING ACTION ALREADY DOES ────────────────────
   ON-04 provisions the Drive folder, the Slack channel and the LeadLock
   sub-account once per client. Both onboarding templates ALSO contain
   checklist steps for those same artifacts — so the Blueprint's claim that
   "workspace provisioning is not represented in ClickUp tasks" is
   contradicted by the imported lists, and running both would create the
   folder twice.

   Matching is by name against the task titles actually present in the
   snapshot, so this list is checkable rather than asserted. */
export const PROVISIONED_ARTIFACTS = Object.freeze([
  {
    key: "drive_folder",
    label: "Google Drive client folder",
    /* CREATION only. "Share Google Drive Folder (add client email address)"
       is a separate step that still has to happen after provisioning, and
       ticking it off would leave the client without access. */
    matches: [/^create .*drive folder/i, /^create .*google drive/i],
  },
  {
    key: "slack_channel",
    label: "Slack channel",
    matches: [/^create slack channel/i],
  },
  {
    key: "leadlock_subaccount",
    label: "LeadLock sub-account",
    matches: [/^create leadlock sub-?account/i],
  },
]);

/** Tasks a single provisioning run would satisfy, so they are ticked rather
    than run again. Returns `{ [taskId]: artifactKey }`. */
export const provisioningOverlap = (draft) => {
  const map = {};
  for (const task of draft?.tasks ?? []) {
    for (const artifact of PROVISIONED_ARTIFACTS) {
      if (artifact.matches.some((re) => re.test(task.title))) {
        map[task.id] = artifact.key;
        break;
      }
    }
  }
  return map;
};
