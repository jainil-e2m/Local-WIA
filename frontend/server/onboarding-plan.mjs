/* Offer set -> onboarding task draft, built from their REAL ClickUp templates.
 *
 * Supersedes the transcript-derived placeholder this file used to hold. Every
 * task, role, phase and destination below was read out of the Wedding Industry
 * Ads workspace over the ClickUp API (GET only) and baked into
 * onboarding-templates.json by onboarding-templates-generate.mjs. Re-run that
 * script when they edit a template.
 *
 * ── THE DESTINATION, MEASURED ─────────────────────────────────────────────
 * Not one merged list. Ridgefield Weddings and Events, a live ELEVATE client,
 * is laid out as:
 *
 *     ELEVATE Clients                      (space, chosen by offer)
 *       └── Ridgefield Weddings and Events (folder, one per client)
 *             ├── LeadLock Onboarding      (list, from template)
 *             ├── Google + Meta Onboarding (list, from template)
 *             └── Client Management        (list, recurring — NOT onboarding)
 *
 * That resolves the ambiguity in Whitney's "we're going off both of those
 * onboarding templates" (Sept 2 @19:59): it is two lists side by side in one
 * client folder, not two templates merged into a single list. So the both-
 * offers case needs no dedup — the eight name collisions between the templates
 * are fine, because they land in different lists.
 *
 * ── SEVERAL ANCHORS, NOT ONE KICKOFF ──────────────────────────────────────
 * The templates carry ZERO due dates (0 of 308 tasks). Ridgefield's live list
 * carries 29. Diffing the two recovers a weekly cadence — but it recovers it
 * against ONE list, anchored on ONE call.
 *
 * THE DEFECT THAT CORRECTED. Every phase-driven task on BOTH tracks was dated
 * from a single "kickoff" date. That is not the sequence discovery describes
 * (Sept 2 @33:01 onward). There are at least seven distinct anchors, they are
 * booked by different people at different times, and two of them are not
 * dates at all — they are client decisions that arrive when they arrive:
 *
 *   signed_and_paid        the alert pair. Known at wave 1.
 *   ads_kickoff            booked BY THE CLIENT via the welcome-email link
 *   messaging_positioning  a second Whitney call, booked separately
 *   ad_strategy            "shortly after" M&P — Carmen attends
 *   leadlock_kickoff       Danielle's call, running in PARALLEL, not after
 *   internal_tests         a team milestone
 *   launch_approval        the client signing off. A WAITING STATE.
 *
 * Dating a LeadLock task from the ads kickoff produced a deadline nobody
 * agreed to, and a postponed positioning call could not move anything that
 * depended on it. Each phase now names the anchor it hangs off, and a task
 * whose phase has no anchor says "no scheduling rule" rather than pretending
 * to wait for a kickoff it will never use.
 *
 * ── THE WAVES ─────────────────────────────────────────────────────────────
 *   WAVE 1, at signature   create the lists, resolve owners from Role, mark
 *                          every phase-driven task as awaiting ITS anchor
 *   WAVE 2+, as calls book each anchor date fills in the tasks that hang off
 *                          it, and only those. Approving wave 1 does NOT end
 *                          the record — see onboarding-store.mjs.
 *
 * Wave 2 is the part that is worth something. It is also exactly the "return
 * visit days later" that makes this a 2-hours-depending job rather than one
 * sitting — the shape of work a person forgets.
 *
 * ── WHAT THIS MODULE DECIDES vs WHAT CLICKUP ALREADY KNOWS ────────────────
 * ClickUp already knows: the task list, its order, its subtask nesting, and
 * the Role that owns each task (299 of 308 tasks carry one).
 * This module adds: Role -> a named person (a real person is set on only 190
 * of 308, so the 109-task gap is the contribution), and Phase -> a due date.
 * Nothing else. Where the template is already complete, this does nothing, and
 * it should say so rather than pretend otherwise.
 */

