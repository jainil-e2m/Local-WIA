import { test } from 'node:test';
import assert from 'node:assert/strict';
import { existsSync, readFileSync, readdirSync, statSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

/* 1.F1, done when: no hand-written API type remains. The types of every answer the backend gives are generated from
   backend/openapi.json (src/api/schema.d.ts); the app names them in src/api/types.ts and nowhere describes them again. */

const src = path.join(path.dirname(fileURLToPath(import.meta.url)), '..');
const schemaText = readFileSync(path.join(src, 'api', 'schema.d.ts'), 'utf8');
const generated = new Set([...schemaText.matchAll(/^export type (\w+) = components\['schemas'\]/gm)].map(match => match[1]));

function* sourceFiles(directory: string): Generator<string> {
  for (const entry of readdirSync(directory)) {
    const full = path.join(directory, entry);
    if (statSync(full).isDirectory()) yield* sourceFiles(full);
    else if (/\.(ts|tsx)$/.test(entry) && !/\.test\.tsx?$/.test(entry)) yield full;
  }
}
const relative = (file: string) => path.relative(src, file).replaceAll('\\', '/');
// The generated file, the names given to its types, the mock library, the test helpers.
const EXEMPT = new Set(['api/schema.d.ts', 'api/types.ts']);
const files = [...sourceFiles(src)].filter(file => !EXEMPT.has(relative(file)) && !/^(data|testing)\//.test(relative(file)));

test('1.F1: the schema is generated and names the backend\'s answers', () => {
  assert.match(schemaText.split('\n')[0], /Generated by `npm run api:types` from backend\/openapi\.json/);
  for (const name of ['StoredWeek', 'WeekReview', 'StoredAngle', 'StoredBriefV1', 'StoredBriefV2', 'StoredBriefV3', 'StoredBriefV4', 'StoredPackV2', 'PackSummaryV2', 'WeekPackPlanV2', 'SavedSchedule', 'ContextItem', 'KbVersion', 'Me', 'Flags', 'IntakeOverview']) {
    assert.ok(generated.has(name), `${name} should be generated`);
  }
});

test('1.F1: no type outside src/api repeats a name the backend publishes', () => {
  const repeated: string[] = [];
  for (const file of files) {
    for (const match of readFileSync(file, 'utf8').matchAll(/^\s*export (?:interface|type) (\w+)(.*)$/gm)) {
      // An alias of the generated type itself (export type X = components['schemas']['X']) is the intended way to name it.
      if (generated.has(match[1]) && !/components\['schemas'\]/.test(match[2])) repeated.push(`${relative(file)}: ${match[1]}`);
    }
  }
  assert.deepEqual(repeated, []);
});

test('1.F1: the hand-written API type files are gone; src/types keeps only the mock library\'s types', () => {
  for (const removed of ['weeklyStorage', 'briefStorage', 'context', 'production']) assert.ok(!existsSync(path.join(src, 'types', `${removed}.ts`)), removed);
  assert.deepEqual(readdirSync(path.join(src, 'types')).sort(), ['atelier.ts', 'calendar.ts']);
});

test('1.F1: a request names its answer through a generated type, never an inline shape', () => {
  const inline: string[] = [];
  for (const file of files) {
    for (const match of readFileSync(file, 'utf8').matchAll(/(?:storageRequest|apiRequest)<\s*(\{[^>]*\}|\w+\[\])/g)) inline.push(`${relative(file)}: ${match[0]}`);
  }
  assert.deepEqual(inline, []);
});

test('1.F3: the documents types are the generated ones, with no hand-written copy', () => {
  assert.ok(schemaText.includes('"/storage/documents"'), 'The schema must hold GET /storage/documents (npm run api:types)');
  assert.ok(!existsSync(path.join(src, 'api', 'documents.pending.ts')));
  const documents = readFileSync(path.join(src, 'api', 'documents.ts'), 'utf8');
  assert.match(documents, /components\['schemas'\]\['DocumentSummary'\]/);
  assert.doesNotMatch(documents, /interface Document/);
});
