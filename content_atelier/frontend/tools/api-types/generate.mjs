// Generates src/api/schema.d.ts from ../backend/openapi.json (plan 1.F1). Run through `npm run api:types`.
// The output is committed; CI regenerates it and fails when the committed file differs.
import { writeFileSync } from 'node:fs';
import openapiTS, { astToString } from 'openapi-typescript';

const source = new URL('../../../backend/openapi.json', import.meta.url);
const target = new URL('../../src/api/schema.d.ts', import.meta.url);

const ast = await openapiTS(source, { rootTypes: true, rootTypesNoSchemaPrefix: true });
const header = '// Generated by `npm run api:types` from backend/openapi.json. Do not edit; change the backend and regenerate.\n\n';
writeFileSync(target, header + astToString(ast).replaceAll('\r\n', '\n'));
console.log('Wrote src/api/schema.d.ts');
